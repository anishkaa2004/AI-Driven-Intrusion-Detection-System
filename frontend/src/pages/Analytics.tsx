import { useState } from "react";
import { useFetch } from "../app/useFetch";
import { ConfusionMatrix, HBars } from "../components/charts";
import { Card, Empty, ErrorBox, PageHeader, Spinner, Stat, cx, fmtTime, td, th } from "../components/ui";
import { api } from "../services/api";
import type { Experiment, ModelMetrics } from "../types";

const pct = (v: number | null | undefined, digits = 1) => (v == null ? "—" : `${(v * 100).toFixed(digits)}%`);

export default function AnalyticsPage() {
  const { data, error } = useFetch(() => api.get<ModelMetrics>("/models/metrics"), []);
  const [picked, setPicked] = useState<string | null>(null);

  if (!data) return error ? <ErrorBox error={error} /> : <div className="flex justify-center py-20"><Spinner /></div>;
  const m = data.active.manifest;
  const experiments = m.experiments ?? [];
  const current: Experiment | undefined = experiments.find((e) => e.model_name === (picked ?? m.model_name)) ?? experiments[0];
  const synthetic = m.dataset === "synthetic";

  return (
    <>
      <PageHeader title="ML analytics" subtitle="Evaluation of the deployed model on its held-out test split, and documentation of every rule" />
      {!data.active.loaded && (
        <Card className="mb-4">
          <Empty title="No model loaded — detection is rule-only">
            {data.active.load_error} Train one with <code className="rounded bg-slate-100 px-1 dark:bg-slate-800">python ml/src/train.py</code> and restart the backend.
          </Empty>
        </Card>
      )}
      {data.active.loaded && (
        <>
          {synthetic && (
            <div className="mb-4 rounded-lg border border-amber-300 bg-amber-50 px-3 py-2 text-sm text-amber-800 dark:border-amber-800 dark:bg-amber-950/40 dark:text-amber-200">
              This model was trained and evaluated on <strong>synthetic</strong> data generated by this project. The metrics below show the pipeline
              works; they do not measure real-world detection performance. Retrain with <code>--dataset cicids2017</code> for reportable results.
            </div>
          )}
          <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
            <Stat label="Deployed model" value={<span className="text-base">{m.model_name?.replace(/_/g, " ")}</span>} hint={`schema ${m.feature_schema_version} · trained ${fmtTime(m.trained_at)}`} />
            <Stat label="Macro F1 (test)" value={m.metrics?.macro.f1.toFixed(3)} hint={`${m.metrics?.test_rows.toLocaleString()} held-out flows`} />
            <Stat label="False-positive rate" value={pct(m.metrics?.false_positive_rate, 2)} hint="benign flows flagged as any attack" />
            <Stat label="Inference latency" value={`${m.metrics?.latency?.single_row_ms_median ?? "—"} ms`}
              hint={`median per flow · last batch ${data.active.last_inference_latency_ms?.toFixed(1) ?? "—"} ms`} />
          </div>
          <p className="mt-2 text-xs text-slate-500">Dataset: {m.dataset_reference}. Split: {String(m.split?.method)} (seed {String(m.split?.seed)}).</p>

          <Card title="Model comparison (same test split)" className="mt-4">
            <div className="-mx-4 overflow-x-auto">
              <table className="w-full min-w-[720px] text-sm tabular">
                <thead className="border-b border-slate-100 dark:border-slate-800">
                  <tr>
                    <th className={th}>Model</th><th className={th}>Precision</th><th className={th}>Recall</th><th className={th}>F1</th>
                    <th className={th}>FPR</th><th className={th}>Detection rate</th><th className={th}>PR-AUC</th><th className={th}>Latency (1 row)</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                  {experiments.map((e) => (
                    <tr key={e.model_name} onClick={() => e.model_name !== "isolation_forest" && setPicked(e.model_name)}
                      className={cx(e.model_name !== "isolation_forest" && "cursor-pointer hover:bg-slate-50 dark:hover:bg-slate-800/40",
                        current?.model_name === e.model_name && "bg-teal-50/60 dark:bg-teal-950/30")}>
                      <td className={td}>
                        <span className="font-medium">{e.model_name.replace(/_/g, " ")}</span>
                        {e.selected && <span className="ml-2 rounded bg-teal-600 px-1.5 py-0.5 text-[10px] font-semibold text-white">DEPLOYED</span>}
                        {e.model_name === "isolation_forest" && <div className="text-xs text-slate-500">anomaly experiment · binary · not deployed</div>}
                      </td>
                      <td className={td}>{e.test.macro.precision.toFixed(3)}</td>
                      <td className={td}>{e.test.macro.recall.toFixed(3)}</td>
                      <td className={td + " font-medium"}>{e.test.macro.f1.toFixed(3)}</td>
                      <td className={td}>{pct(e.test.false_positive_rate, 2)}</td>
                      <td className={td}>{pct(e.test.detection_rate, 2)}</td>
                      <td className={td}>{e.test.binary_pr_auc?.toFixed(3) ?? "—"}</td>
                      <td className={td}>{e.test.latency?.single_row_ms_median} ms</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <p className="mt-2 text-xs text-slate-500">Macro = unweighted mean over classes. FPR and detection rate use a binary benign-vs-attack view. The deployed model was chosen on validation macro-F1, not on these test numbers.</p>
          </Card>

          {current && (
            <div className="mt-4 grid gap-4 lg:grid-cols-2">
              <Card title={`Per-class metrics — ${current.model_name.replace(/_/g, " ")}`}>
                <table className="w-full text-sm tabular">
                  <thead><tr><th className={th}>Class</th><th className={th}>Precision</th><th className={th}>Recall</th><th className={th}>F1</th><th className={th}>Support</th></tr></thead>
                  <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                    {Object.entries(current.test.per_class).map(([k, v]) => (
                      <tr key={k}><td className={td + " font-medium"}>{k}</td><td className={td}>{v.precision.toFixed(3)}</td>
                        <td className={td}>{v.recall.toFixed(3)}</td><td className={td}>{v.f1.toFixed(3)}</td><td className={td}>{v.support.toLocaleString()}</td></tr>
                    ))}
                  </tbody>
                </table>
              </Card>
              <Card title="Confusion matrix (test)">
                <ConfusionMatrix labels={current.test.labels} matrix={current.test.confusion_matrix} />
              </Card>
              {current.feature_importance && (
                <Card title="Global feature importance" className="lg:col-span-2">
                  <HBars rows={Object.entries(current.feature_importance).map(([k, v]) => ({ label: k.replace(/_/g, " "), value: v }))}
                    format={(n) => n.toFixed(3)} color="#6366f1" />
                  <p className="mt-3 text-xs text-slate-500">Impurity-based (trees) or mean |coefficient| (logistic regression). These are approximate, global explanations and can be biased toward high-cardinality features.</p>
                </Card>
              )}
            </div>
          )}
        </>
      )}

      <Card title="Detection rules" className="mt-4">
        <div className="space-y-4">
          {data.rules.map((r) => (
            <div key={r.rule_id} className="rounded-lg border border-slate-200 p-3 dark:border-slate-800">
              <div className="flex flex-wrap items-baseline gap-2">
                <span className="font-mono text-xs text-slate-500">{r.rule_id}</span>
                <span className="font-medium">{r.name}</span>
              </div>
              <p className="mt-1 text-sm text-slate-600 dark:text-slate-300">{r.logic}</p>
              <div className="mt-2 grid gap-2 text-xs sm:grid-cols-2">
                <div><span className="text-slate-500">Required fields: </span>{r.required_fields.join(", ")}</div>
                <div><span className="text-slate-500">Known benign causes: </span>{r.benign_causes.join("; ")}</div>
              </div>
            </div>
          ))}
        </div>
      </Card>

      {data.registry.length > 0 && (
        <Card title="Model registry" className="mt-4">
          <ul className="space-y-1 text-sm">
            {data.registry.map((r) => (
              <li key={r.id} className="flex flex-wrap justify-between gap-2">
                <span className="font-mono text-xs">{r.model_version}</span>
                <span className="text-xs text-slate-500">{r.is_active ? "active" : "inactive"} · {r.dataset_reference}</span>
              </li>
            ))}
          </ul>
        </Card>
      )}
    </>
  );
}
