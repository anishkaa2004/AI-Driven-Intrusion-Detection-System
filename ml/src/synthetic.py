"""Synthetic flow-v1 data for development, tests and safe demonstrations.

IMPORTANT: this data is generated by simple statistical recipes. It lets the
pipeline run end-to-end without downloading a dataset, but metrics measured on
it say nothing about real-world detection performance. Train on a public
benchmark (e.g. CICIDS2017, see prepare_data.py) for reportable results.

Two things live here:
  * `make_training_frame` - labelled per-flow rows for model training.
  * `scenario_*` functions - timestamped event sequences for replay demos
    that exercise the rule engine (port scan, flood, failures, DNS).
"""

import uuid
from datetime import datetime, timedelta, timezone

import numpy as np
import pandas as pd

LABELS = ["BENIGN", "PortScan", "DoS", "BruteForce"]
BENIGN_PORTS = [443, 443, 443, 443, 80, 53, 53, 22, 123, 993, 5223, 8443]


def _benign(rng: np.random.Generator, n: int) -> pd.DataFrame:
    port = rng.choice(BENIGN_PORTS, n)
    dns = port == 53
    dur = np.where(dns, rng.exponential(0.03, n), rng.lognormal(0.5, 1.6, n))
    p_out = np.where(dns, 1, np.maximum(1, rng.lognormal(2.3, 1.1, n).astype(int)))
    p_in = np.where(dns, rng.integers(0, 2, n), np.maximum(0, (p_out * rng.uniform(0.6, 3.0, n)).astype(int)))
    b_out = np.where(dns, rng.integers(50, 90, n), p_out * rng.integers(60, 700, n))
    b_in = np.where(dns, p_in * rng.integers(80, 300, n), p_in * rng.integers(200, 1450, n))
    # A few benign short probes / failed connections to arbitrary ports.
    odd = rng.random(n) < 0.03
    port = np.where(odd, rng.integers(1024, 65535, n), port)
    return pd.DataFrame({"flow_duration": dur, "packets_in": p_in, "packets_out": p_out,
                         "bytes_in": b_in, "bytes_out": b_out, "dst_port": port})


def _portscan(rng, n):
    return pd.DataFrame({
        "flow_duration": rng.exponential(0.004, n),
        "packets_in": rng.integers(0, 2, n),
        "packets_out": rng.integers(1, 3, n),
        "bytes_in": rng.integers(0, 2, n) * rng.integers(40, 60, n),
        "bytes_out": rng.integers(40, 80, n),
        "dst_port": rng.integers(1, 65535, n),
    })


def _dos(rng, n):
    slow = rng.random(n) < 0.3  # slowloris-like: long, low volume
    p_out = np.where(slow, rng.integers(3, 12, n), rng.integers(20, 400, n))
    return pd.DataFrame({
        "flow_duration": np.where(slow, rng.uniform(20, 120, n), rng.uniform(0.05, 3.0, n)),
        "packets_in": np.where(slow, rng.integers(1, 6, n), rng.integers(0, 8, n)),
        "packets_out": p_out,
        "bytes_in": rng.integers(0, 2000, n),
        "bytes_out": p_out * rng.integers(40, 300, n),
        "dst_port": rng.choice([80, 80, 80, 443, 8080], n),
    })


def _bruteforce(rng, n):
    p = rng.integers(8, 24, n)
    return pd.DataFrame({
        "flow_duration": rng.uniform(0.8, 6.0, n),
        "packets_in": p + rng.integers(-2, 3, n),
        "packets_out": p,
        "bytes_in": p * rng.integers(70, 160, n),
        "bytes_out": p * rng.integers(60, 140, n),
        "dst_port": rng.choice([22, 22, 22, 21, 3389], n),
    })


def make_training_frame(n: int = 60_000, seed: int = 42, label_noise: float = 0.01) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    shares = {"BENIGN": 0.70, "PortScan": 0.12, "DoS": 0.12, "BruteForce": 0.06}
    gens = {"BENIGN": _benign, "PortScan": _portscan, "DoS": _dos, "BruteForce": _bruteforce}
    parts = []
    for label, share in shares.items():
        df = gens[label](rng, int(n * share))
        df["label"] = label
        parts.append(df)
    df = pd.concat(parts, ignore_index=True)
    noisy = rng.random(len(df)) < label_noise
    df.loc[noisy, "label"] = rng.choice(LABELS, noisy.sum())
    for c in ("packets_in", "packets_out", "bytes_in", "bytes_out"):
        df[c] = df[c].clip(lower=0).astype(int)
    return df.sample(frac=1.0, random_state=seed).reset_index(drop=True)


# --------------------------------------------------------------- replay demos
def _iso(t: datetime) -> str:
    return t.astimezone(timezone.utc).isoformat().replace("+00:00", "Z")


def _event(t, proto, src, dst, sport, dport, row, **extra) -> dict:
    return {
        "event_id": f"demo-{uuid.uuid4().hex}",
        "event_time": _iso(t),
        "protocol": proto,
        "src_ip": src, "dst_ip": dst, "src_port": int(sport), "dst_port": int(dport),
        "flow_duration": round(float(row["flow_duration"]), 6),
        "packets_in": int(row["packets_in"]), "packets_out": int(row["packets_out"]),
        "bytes_in": int(row["bytes_in"]), "bytes_out": int(row["bytes_out"]),
        **extra,
    }


def scenario_normal(start: datetime, device_ip="192.168.56.10", n=120, seed=1) -> list[dict]:
    rng = np.random.default_rng(seed)
    rows = _benign(rng, n)
    out = []
    for i, row in rows.iterrows():
        t = start + timedelta(seconds=float(i) * 0.5)
        port = int(row["dst_port"])
        proto = "UDP" if port in (53, 123) else "TCP"
        dst = "192.168.56.1" if port == 53 else f"203.0.113.{rng.integers(1, 250)}"
        extra = {"conn_state": "established"} if proto == "TCP" else {}
        if port == 53:
            extra["dns_rcode"] = "NOERROR"
        out.append(_event(t, proto, device_ip, dst, rng.integers(49152, 65535), port, row, **extra))
    return out


def scenario_port_scan(start, attacker="192.168.56.66", target="192.168.56.10", n=200, seed=2):
    rng = np.random.default_rng(seed)
    rows = _portscan(rng, n)
    ports = rng.permutation(np.arange(1, 1025))[:n]
    return [_event(start + timedelta(milliseconds=int(i) * 50), "TCP", attacker, target,
                   rng.integers(40000, 60000), ports[i], row,
                   conn_state="reset" if rng.random() < 0.9 else "established")
            for i, row in rows.iterrows()]


def scenario_flood(start, target="192.168.56.20", n=300, seed=3):
    rng = np.random.default_rng(seed)
    rows = _dos(rng, n)
    sources = [f"198.51.100.{i}" for i in rng.integers(1, 40, n)]
    return [_event(start + timedelta(milliseconds=int(i) * 20), "TCP", sources[i], target,
                   rng.integers(1024, 65535), 80, row, conn_state="established")
            for i, row in rows.iterrows()]


def scenario_conn_failures(start, attacker="192.168.56.77", target="192.168.56.10", n=40, seed=4):
    rng = np.random.default_rng(seed)
    rows = _bruteforce(rng, n)
    return [_event(start + timedelta(milliseconds=int(i) * 900), "TCP", attacker, target,
                   rng.integers(40000, 60000), 22, row,
                   conn_state="failed" if rng.random() < 0.7 else "reset")
            for i, row in rows.iterrows()]


def scenario_dns(start, device_ip="192.168.56.10", resolver="192.168.56.1", n=200, seed=5):
    rng = np.random.default_rng(seed)
    out = []
    for i in range(n):
        row = {"flow_duration": rng.exponential(0.02), "packets_in": 1, "packets_out": 1,
               "bytes_in": int(rng.integers(90, 200)), "bytes_out": int(rng.integers(60, 120))}
        out.append(_event(start + timedelta(milliseconds=i * 150), "UDP", device_ip, resolver,
                          rng.integers(49152, 65535), 53, row,
                          dns_rcode="NXDOMAIN" if rng.random() < 0.6 else "NOERROR"))
    return out


SCENARIOS = {
    "normal": scenario_normal,
    "port_scan": scenario_port_scan,
    "flood": scenario_flood,
    "conn_failures": scenario_conn_failures,
    "dns": scenario_dns,
}
